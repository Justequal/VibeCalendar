/** Refresh the compact, source-backed festival table. Never run during app startup. */
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const SOURCE = 'https://www.hko.gov.hk/en/gts/time/calendar/text/files/';

function parseCalendar(text, year) {
  const result = {};
  let lunarMonth;
  for (const line of text.split(/\r?\n/)) {
    const match = /^(\d{4})\/(\d+)\/(\d+)\s+(.+?)\s{2,}/.exec(line);
    if (!match || Number(match[1]) !== year) continue;
    const date = `${match[2].padStart(2, '0')}-${match[3].padStart(2, '0')}`;
    const lunar = match[4].trim().toLowerCase();
    if (/lunar month/.test(lunar)) lunarMonth = lunar;
    if (lunar === '1st lunar month') result.springFestival ||= date;
    if (lunar === '5' && lunarMonth === '5th lunar month') result.dragonBoat ||= date;
    if (lunar === '15' && lunarMonth === '8th lunar month') result.midAutumn ||= date;
    if (/Bright\s*&\s*Clear/.test(line)) result.qingming = date;
  }
  if (Object.keys(result).length !== 4) throw new Error(`Incomplete HKO calendar: ${year}`);
  return result;
}

async function run() {
  const years = Array.from({ length: 200 }, (_, index) => index + 1901);
  const records = {};
  const cacheDirectory = path.join(os.tmpdir(), 'vibe-hko-calendar-source');
  fs.mkdirSync(cacheDirectory, { recursive: true });
  const errors = [];
  let next = 0;
  await Promise.all(Array.from({ length: 4 }, async () => {
    while (next < years.length) {
      const year = years[next++];
      let lastError;
      for (let attempt = 0; attempt < 3; attempt += 1) {
        try {
          const cached = path.join(cacheDirectory, `${year}.txt`);
          let raw;
          if (fs.existsSync(cached)) raw = fs.readFileSync(cached, 'utf8');
          else {
            const response = await fetch(`${SOURCE}T${year}e.txt`, { signal: AbortSignal.timeout(20000) });
            if (!response.ok) throw new Error(`HKO HTTP ${response.status}`);
            raw = await response.text();
          }
          records[year] = parseCalendar(raw, year);
          fs.writeFileSync(cached, raw);
          lastError = null;
          break;
        } catch (error) { lastError = error; }
      }
      if (lastError) errors.push(`${year}: ${lastError.message}`);
      if (Object.keys(records).length % 25 === 0) console.log(`Validated ${Object.keys(records).length}/200 years`);
    }
  }));
  if (errors.length) throw new Error(errors.join('\n'));
  const source = `// Source: ${SOURCE}T{year}e.txt (Hong Kong Observatory, 1901–2100).\n`
    + '// Generated by scripts/sync-festival-dates.js. Future astronomical dates may be revised by HKO.\n'
    + '(function exposeFestivalDates(root) {\n  const years = {\n'
    + years.map(year => `    "${year}": Object.freeze(${JSON.stringify(records[year])})`).join(',\n')
    + '\n  };\n  const data = Object.freeze(years);\n'
    + "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n"
    + '  if (root) root.VibeFestivalDates = data;\n})(typeof window !== \'undefined\' ? window : globalThis);\n';
  fs.writeFileSync(path.resolve(__dirname, '../src/renderer/festival-dates.js'), source);
}

if (require.main === module) run().catch(error => { console.error(error); process.exitCode = 1; });
module.exports = { parseCalendar };
